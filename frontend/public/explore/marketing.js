function updateEducationalImages() {
  const dark = document.documentElement.dataset.theme === "dark";
  document.querySelectorAll('img[data-theme-image="educational"]').forEach((image) => {
    const originalPath = image.dataset.originalSrc;
    if (!originalPath) return;
    const request = Number(image.dataset.themeRequest || 0) + 1;
    image.dataset.themeRequest = String(request);
    if (!dark) {
      if (image.getAttribute("src") !== originalPath) image.src = originalPath;
      image.dataset.themeReady = "true";
      return;
    }
    if (image.dataset.themeDarkSource === originalPath && image.getAttribute("src")?.startsWith("data:image/svg+xml")) {
      image.dataset.themeReady = "true";
      return;
    }
    image.dataset.themeReady = "false";
    window.EfhamaImageTheme.darkSource(originalPath).then((darkSource) => {
      if (image.dataset.themeRequest === String(request)
        && document.documentElement.dataset.theme === "dark"
        && image.dataset.originalSrc === originalPath) {
        image.src = darkSource;
        image.dataset.themeDarkSource = originalPath;
        image.dataset.themeReady = "true";
      }
    }).catch((error) => {
      console.error("Unable to adapt public educational visual for dark mode:", error);
      if (image.dataset.themeRequest === String(request) && image.dataset.originalSrc === originalPath) {
        image.dataset.themeReady = "true";
      }
    });
  });
}

function render() {
  document.documentElement.lang = "ar";
  document.documentElement.dir = "rtl";
  document.querySelectorAll("[data-copy]").forEach((node) => {
    const value = copy[language][node.dataset.copy];
    if (value !== undefined) node.innerHTML = value;
  });
  document.querySelectorAll("[data-copy-aria]").forEach((node) => {
    node.setAttribute("aria-label", copy[language][node.dataset.copyAria]);
  });
  document.querySelectorAll("[data-copy-content]").forEach((node) => {
    node.setAttribute("content", copy[language][node.dataset.copyContent]);
  });
  document.querySelectorAll(".primary-nav").forEach((node) => {
    node.setAttribute("aria-label", copy[language].menuLabel);
  });
  document.querySelectorAll("[data-theme-toggle]").forEach((node) => {
    node.setAttribute("aria-label", copy[language].themeLabel);
  });

  document.querySelectorAll("[data-nav]").forEach((node) => {
    if (node.dataset.nav === page) node.setAttribute("aria-current", "page");
    else node.removeAttribute("aria-current");
  });
  const pageTitles = {
    home: "homePageTitle",
    chapters: "chaptersPageTitle",
    paths: "pathsPageTitle",
    projects: "projectsPageTitle",
  };
  document.title = copy[language][pageTitles[page]];
  const pageDescriptions = {
    home: "homeMetaDescription",
    chapters: "chaptersMetaDescription",
    paths: "pathsMetaDescription",
    projects: "projectsMetaDescription",
  };
  document.querySelector('meta[name="description"]')?.setAttribute(
    "content",
    copy[language][pageDescriptions[page]],
  );
  document.querySelectorAll("[data-catalog]").forEach((root) => {
    root.replaceChildren();
    if (root.dataset.catalog === "chapters") renderChapters(root);
    if (root.dataset.catalog === "paths") renderPaths(root);
    if (root.dataset.catalog === "projects") renderProjects(root);
  });
  updateEducationalImages();
}


