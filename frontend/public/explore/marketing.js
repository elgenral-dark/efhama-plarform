function initializeQrShare() {
  const imageLink = document.getElementById("qrImageLink");
  if (!imageLink) return;

  const image = document.getElementById("qrImage");
  const siteLink = document.getElementById("qrSiteLink");
  const status = document.getElementById("qrShareStatus");
  const copyButton = document.getElementById("qrCopyButton");
  const shareButton = document.getElementById("qrShareButton");
  const downloadButton = document.getElementById("qrDownloadButton");
  const localized = (key) => copy[language][key];
  const setStatus = (message, isError = false) => {
    status.textContent = message;
    status.dataset.state = isError ? "error" : "ready";
  };
  const copyUrl = async (url) => {
    if (navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(url);
      return;
    }
    const field = document.createElement("textarea");
    field.value = url;
    field.setAttribute("readonly", "");
    field.style.position = "fixed";
    field.style.opacity = "0";
    document.body.append(field);
    field.select();
    const copied = document.execCommand("copy");
    field.remove();
    if (!copied) throw new Error("Clipboard copy command was rejected.");
  };
  const createQrPng = (qr, cellSize) => {
    const moduleCount = qr.getModuleCount();
    const quietZone = 4;
    const canvas = document.createElement("canvas");
    const size = (moduleCount + quietZone * 2) * cellSize;
    canvas.width = size;
    canvas.height = size;
    const context = canvas.getContext("2d");
    if (!context) throw new Error("Canvas is unavailable for QR image rendering.");
    context.fillStyle = "#fff";
    context.fillRect(0, 0, size, size);
    context.fillStyle = "#000";
    for (let row = 0; row < moduleCount; row += 1) {
      for (let column = 0; column < moduleCount; column += 1) {
        if (qr.isDark(row, column)) {
          context.fillRect((column + quietZone) * cellSize, (row + quietZone) * cellSize, cellSize, cellSize);
        }
      }
    }
    return canvas.toDataURL("image/png");
  };

  let siteUrl;
  try {
    const configuredUrl = typeof window.EFHAMA_SITE_URL === "string" ? window.EFHAMA_SITE_URL.trim() : "";
    const parsedUrl = new URL(configuredUrl || window.location.origin);
    const hostname = parsedUrl.hostname.toLowerCase();
    const isLocalHost = hostname === "localhost" || hostname.endsWith(".localhost")
      || hostname.startsWith("[") || /^127\./.test(hostname) || /^10\./.test(hostname)
      || /^192\.168\./.test(hostname) || /^172\.(1[6-9]|2\d|3[01])\./.test(hostname)
      || /^\d{1,3}(?:\.\d{1,3}){3}$/.test(hostname);
    if (parsedUrl.protocol !== "https:" || isLocalHost || parsedUrl.username || parsedUrl.password
      || parsedUrl.search || parsedUrl.hash) throw new Error("A secure production URL is required.");
    siteUrl = parsedUrl.href.replace(/\/+$/, "");
  } catch (error) {
    console.error("Unable to configure the Efhama QR code:", error);
    setStatus(localized("qrUnavailable"), true);
    return;
  }

  try {
    if (typeof window.qrcode !== "function") throw new Error("The QR code generator did not load.");
    const qr = window.qrcode(0, "H");
    qr.addData(siteUrl, "Byte");
    qr.make();
    image.src = createQrPng(qr, 8);
    imageLink.href = siteUrl;
    imageLink.setAttribute("aria-label", localized("qrOpen"));
    imageLink.hidden = false;
    siteLink.href = siteUrl;
    siteLink.textContent = siteUrl;
    siteLink.hidden = false;
    setStatus(localized("qrReady"));

    copyButton.addEventListener("click", async () => {
      try {
        await copyUrl(siteUrl);
        setStatus(localized("qrCopied"));
      } catch (error) {
        console.error("Unable to copy the Efhama URL:", error);
        setStatus(localized("qrCopyFailed"), true);
      }
    });

    shareButton.addEventListener("click", async () => {
      try {
        if (navigator.share) await navigator.share({ title: "Efhama", url: siteUrl });
        else await copyUrl(siteUrl);
        setStatus(localized("qrCopied"));
      } catch (error) {
        if (error.name === "AbortError") return;
        console.error("Unable to share the Efhama URL:", error);
        setStatus(localized("qrShareFailed"), true);
      }
    });

    downloadButton.addEventListener("click", () => {
      try {
        const downloadQr = window.qrcode(0, "H");
        downloadQr.addData(siteUrl, "Byte");
        downloadQr.make();
        const downloadLink = document.createElement("a");
        downloadLink.href = createQrPng(downloadQr, 16);
        downloadLink.download = "efhama-qr-code.png";
        downloadLink.click();
      } catch (error) {
        console.error("Unable to download the Efhama QR code:", error);
        setStatus(localized("qrDownloadFailed"), true);
      }
    });
  } catch (error) {
    console.error("Unable to generate the Efhama QR code:", error);
    setStatus(localized("qrUnavailable"), true);
  }
}

function initializeHeroTypewriter() {
  const container = document.getElementById("heroCodeBody");
  if (!container) return;

  const codeData = [
    { ln: 1, tokens: [{ text: "# ", cls: "tok-comment" }, { text: "البرمجة تفكير وتطبيق مش مجرد سطور", cls: "tok-comment", isBdi: true }] },
    { ln: 2, tokens: [{ text: "def", cls: "tok-kw" }, { text: " " }, { text: "efhamha", cls: "tok-fn" }, { text: "(" }, { text: "concept", cls: "tok-param" }, { text: "):" }] },
    { ln: 3, tokens: [{ text: "  " }, { text: "skills", cls: "tok-var" }, { text: " = [" }, { text: '"Logic"', cls: "tok-str" }, { text: ", " }, { text: '"Python"', cls: "tok-str" }, { text: ", " }, { text: '"AI"', cls: "tok-str" }, { text: "]" }] },
    { ln: 4, tokens: [{ text: "  " }, { text: "if", cls: "tok-kw" }, { text: " " }, { text: "understand", cls: "tok-fn" }, { text: "(" }, { text: "concept", cls: "tok-param" }, { text: "):" }] },
    { ln: 5, tokens: [{ text: "    " }, { text: "return", cls: "tok-kw" }, { text: ' "' }, { text: "تفكير منطقي وحل مشكلات", cls: "tok-str", isBdi: true }, { text: '"', cls: "tok-str" }] },
    { ln: 6, tokens: [] },
    { ln: 7, tokens: [{ text: "print", cls: "tok-kw" }, { text: "(" }, { text: "efhamha", cls: "tok-fn" }, { text: "(" }, { text: '"Logic"', cls: "tok-str" }, { text: "))" }], active: true }
  ];

  const terminalText = "تفكير منطقي وحل مشكلات — النتيجة: إتقان حقيقي";

  if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return;
  }

  let activeTimeout = null;

  function runTypewriter() {
    container.innerHTML = "";

    const lineElements = codeData.map((line) => {
      const lineDiv = document.createElement("div");
      lineDiv.className = "code-line";

      const lnSpan = document.createElement("span");
      lnSpan.className = "code-ln";
      lnSpan.textContent = String(line.ln);

      const textDiv = document.createElement("div");
      textDiv.className = "code-text";

      lineDiv.append(lnSpan, textDiv);
      container.append(lineDiv);
      return { lineDiv, textDiv, lineData: line };
    });

    const terminalDiv = document.createElement("div");
    terminalDiv.className = "code-terminal";
    terminalDiv.innerHTML = `<span class="terminal-prompt">❯</span><span class="terminal-result"><bdi>${terminalText}</bdi></span>`;
    container.append(terminalDiv);

    const cursor = document.createElement("span");
    cursor.className = "type-cursor";

    let currentLineIndex = 0;
    let currentTokenIndex = 0;
    let currentCharIndex = 0;

    function typeNextChar() {
      if (currentLineIndex >= lineElements.length) {
        const lastLine = lineElements[lineElements.length - 1];
        lastLine.lineDiv.classList.add("code-active");
        terminalDiv.classList.add("visible");

        activeTimeout = setTimeout(() => {
          container.style.transition = "opacity 0.4s ease";
          container.style.opacity = "0";
          setTimeout(() => {
            container.style.opacity = "1";
            runTypewriter();
          }, 450);
        }, 5000);
        return;
      }

      const { textDiv, lineData } = lineElements[currentLineIndex];

      if (!lineData.tokens || lineData.tokens.length === 0) {
        currentLineIndex++;
        activeTimeout = setTimeout(typeNextChar, 100);
        return;
      }

      const token = lineData.tokens[currentTokenIndex];

      if (!cursor.parentNode || cursor.parentNode !== textDiv) {
        textDiv.append(cursor);
      }

      let tokenSpan = textDiv.querySelector(`[data-tok="${currentTokenIndex}"]`);
      if (!tokenSpan) {
        tokenSpan = token.isBdi ? document.createElement("bdi") : document.createElement("span");
        if (token.cls) tokenSpan.className = token.cls;
        tokenSpan.dataset.tok = String(currentTokenIndex);
        cursor.before(tokenSpan);
      }

      tokenSpan.textContent += token.text[currentCharIndex];
      currentCharIndex++;

      if (currentCharIndex >= token.text.length) {
        currentTokenIndex++;
        currentCharIndex = 0;

        if (currentTokenIndex >= lineData.tokens.length) {
          currentLineIndex++;
          currentTokenIndex = 0;
          cursor.remove();
          activeTimeout = setTimeout(typeNextChar, 130);
          return;
        }
      }

      const isSpace = token.text[currentCharIndex] === " ";
      const delay = isSpace ? 15 : (Math.random() * 16 + 22);
      activeTimeout = setTimeout(typeNextChar, delay);
    }

    activeTimeout = setTimeout(typeNextChar, 350);
  }

  runTypewriter();
}

